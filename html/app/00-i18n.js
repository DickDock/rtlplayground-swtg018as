// Language selection: explicit override, then browser preference, then English.
function detectLang(){
  try{
    var s=localStorage.getItem("rtl_lang");
    if(s&&LANG[s])return s;
  }catch(e){}
  try{
    var list=(navigator.languages&&navigator.languages.length)?navigator.languages:[navigator.language];
    for(var i=0;i<list.length;i++){
      var l=String(list[i]||"").toLowerCase();
      if(LANG[l])return l;
      var b=l.split("-")[0];
      if(LANG[b])return b;
    }
  }catch(e){}
  return "en";
}
var rtlLang=detectLang();
function t(k,v){
  var s=LANG[rtlLang][k];
  if(s===undefined)s=LANG.en[k];
  if(s===undefined)return k;
  if(v!==undefined)for(var p in v)s=s.split("{"+p+"}").join(v[p]);
  return s;
}
function i18nApply(){
  var els=document.querySelectorAll("[data-i18n],[data-i18n-t],[data-i18n-p]");
  for(var i=0;i<els.length;i++){
    var e=els[i],a=e.dataset;
    if(a.i18n)e.textContent=t(a.i18n);
    if(a.i18nT)e.title=t(a.i18nT);
    if(a.i18nP)e.placeholder=t(a.i18nP);
  }
}
